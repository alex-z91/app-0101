@app.get('/api/status')
def status():
    now = int(time.time())
    with conn() as db:
        cleanup(db, now)
        rows = db.execute(
            'SELECT n.number,o.status FROM numbers n JOIN orders o ON o.id=n.order_id'
        ).fetchall()
        sold = sum(r['status'] == 'paid' for r in rows)
        return jsonify(
            numbers={str(r['number']): r['status'] for r in rows},
            sold=sold,
            occupied=len(rows),
            enabled=CAMPAIGN_ENABLED
        )


@app.post('/api/orders')
def create_order():
    verify_csrf()
    if not CAMPAIGN_ENABLED:
        return jsonify(error='Campanha em modo de demonstração. Reservas e pagamentos não estão habilitados.'), 403

    payload = request.get_json(silent=True) or {}
    nums = payload.get('numbers', [])
    name = str(payload.get('name', '')).strip()
    phone = ''.join(x for x in str(payload.get('phone', '')) if x.isdigit())

    if not isinstance(nums, list) or not 1 <= len(nums) <= 100 or any(type(n) is not int or n < 1 or n > 100 for n in nums) or len(set(nums)) != len(nums):
        return jsonify(error='Seleção de números inválida.'), 400
    if not 3 <= len(name) <= 90 or not 10 <= len(phone) <= 13:
        return jsonify(error='Informe nome e telefone válidos.'), 400

    nums = sorted(nums)
    now = int(time.time())
    oid = uuid.uuid4().hex
    token = secrets.token_urlsafe(24)

    try:
        with conn() as db:
            # O lock serializa as reservas concorrentes; a PK de numbers(number)
            # é a última barreira contra qualquer duplicidade.
            db.execute('LOCK TABLE orders IN SHARE ROW EXCLUSIVE MODE')
            db.execute('LOCK TABLE numbers IN SHARE ROW EXCLUSIVE MODE')
            cleanup(db, now)
            placeholders = ','.join(['%s'] * len(nums))
            existing = db.execute(
                f'SELECT number FROM numbers WHERE number IN ({placeholders})',
                nums
            ).fetchall()
            if existing:
                return jsonify(
                    error='Alguns números acabaram de ser reservados. Atualize a cartela.',
                    unavailable=[r['number'] for r in existing]
                ), 409

            db.execute(
                '''INSERT INTO orders(id,token,name,phone,numbers,amount,status,created_at,expires_at)
                   VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s)''',
                (oid, token, name, phone, ','.join(map(str, nums)), len(nums)*2000,
                 'reserved', now, now + RESERVATION_SECONDS)
            )
            for number in nums:
                db.execute(
                    'INSERT INTO numbers(number,order_id) VALUES(%s,%s)',
                    (number, oid)
                )
            db.execute(
                'INSERT INTO audit(ts,order_id,action) VALUES(%s,%s,%s)',
                (now, oid, 'reserved')
            )
    except UniqueViolation:
        return jsonify(
            error='Um ou mais números acabaram de ser escolhidos por outra pessoa. Confira a disponibilidade.',
            unavailable=nums
        ), 409

    return jsonify(
        order_id=oid,
        token=token,
        expires_at=now + RESERVATION_SECONDS,
        numbers=nums,
        amount=len(nums)*20,
        pix_key=PIX_KEY,
        pix_name=PIX_NAME,
        whatsapp=WHATSAPP
    ), 201


@app.post('/api/orders/<oid>/receipt')
def upload_receipt(oid):
    verify_csrf()
    token = request.form.get('token', '')
    if not token:
        return jsonify(error='Protocolo inválido.'), 403

    f = request.files.get('receipt')
    if not f:
        return jsonify(error='Selecione um comprovante.'), 400

    data = f.read(5*1024*1024 + 1)
    if len(data) > 5*1024*1024 or len(data) < 50:
        return jsonify(error='Arquivo inválido ou maior que 5 MB.'), 400

    if data.startswith(b'%PDF-'):
        ext, ctype = '.pdf', 'application/pdf'
    elif data.startswith(bytes.fromhex('ffd8ff')):
        ext, ctype = '.jpg', 'image/jpeg'
    elif data.startswith(bytes.fromhex('89504e470d0a1a0a')):
        ext, ctype = '.png', 'image/png'
    elif data[:4] == b'RIFF' and data[8:12] == b'WEBP':
        ext, ctype = '.webp', 'image/webp'
    else:
        return jsonify(error='Use PDF, JPG, PNG ou WEBP.'), 400

    now = int(time.time())
    with conn() as db:
        db.execute('LOCK TABLE orders IN SHARE ROW EXCLUSIVE MODE')
        cleanup(db, now)
        order = db.execute(
            'SELECT * FROM orders WHERE id=%s AND token=%s',
            (oid, token)
        ).fetchone()
        if not order or order['status'] not in ('reserved', 'review'):
            return jsonify(error='Reserva não encontrada ou encerrada.'), 404

        receipt_id = secrets.token_hex(20) + ext
        db.execute(
            """UPDATE orders
               SET receipt_file=%s, receipt_type=%s, receipt_original=%s,
                   receipt_data=%s, status='review', expires_at=%s
               WHERE id=%s""",
            (receipt_id, ctype, (f.filename or 'comprovante')[:120],
             data, now + 48*3600, oid)
        )
        db.execute(
            'INSERT INTO audit(ts,order_id,action) VALUES(%s,%s,%s)',
            (now, oid, 'receipt_uploaded')
        )

    return jsonify(ok=True, message='Comprovante recebido. Aguardando conferência manual.'), 200


