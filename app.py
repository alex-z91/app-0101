def initialize():
    with conn() as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS orders (
                id TEXT PRIMARY KEY,
                token TEXT NOT NULL UNIQUE,
                name TEXT NOT NULL,
                phone TEXT NOT NULL,
                numbers TEXT NOT NULL,
                amount INTEGER NOT NULL CHECK (amount > 0),
                status TEXT NOT NULL CHECK (status IN ('reserved','review','paid','cancelled','expired')),
                created_at BIGINT NOT NULL,
                expires_at BIGINT NOT NULL,
                receipt_file TEXT,
                receipt_type TEXT,
                receipt_original TEXT,
                receipt_data BYTEA,
                confirmed_at BIGINT,
                checked_in_at BIGINT
            )
        """)
        db.execute("ALTER TABLE orders ADD COLUMN IF NOT EXISTS checked_in_at BIGINT")
        db.execute("CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status)")
        db.execute("""
            CREATE TABLE IF NOT EXISTS numbers (
                number INTEGER PRIMARY KEY CHECK (number BETWEEN 1 AND 100),
                order_id TEXT NOT NULL REFERENCES orders(id)
            )
        """)
        db.execute("CREATE INDEX IF NOT EXISTS idx_numbers_order_id ON numbers(order_id)")
        db.execute("""
            CREATE TABLE IF NOT EXISTS audit (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ts BIGINT NOT NULL,
                order_id TEXT NOT NULL REFERENCES orders(id),
                action TEXT NOT NULL
            )
        """)


initialize()


@app.after_request
def secure_headers(resp):
    resp.headers['X-Content-Type-Options'] = 'nosniff'
    resp.headers['X-Frame-Options'] = 'DENY'
    resp.headers['Referrer-Policy'] = 'strict-origin-when-cross-origin'
    resp.headers['Cache-Control'] = 'no-store' if request.path.startswith('/api/') or request.path.startswith('/admin') else 'public, max-age=120'
    return resp


def cleanup(db, now):
    expired = db.execute(
        "SELECT id FROM orders WHERE status='reserved' AND expires_at<=%s",
        (now,)
    ).fetchall()
    for order in expired:
        db.execute('DELETE FROM numbers WHERE order_id=%s', (order['id'],))
        db.execute("UPDATE orders SET status='expired' WHERE id=%s", (order['id'],))
        db.execute(
            'INSERT INTO audit(ts,order_id,action) VALUES(%s,%s,%s)',
            (now, order['id'], 'expired')
        )


def csrf():
    if 'csrf' not in session:
        session['csrf'] = secrets.token_urlsafe(28)
    return session['csrf']


def verify_csrf():
    if not secrets.compare_digest(
        (request.headers.get('X-CSRF-Token') or request.form.get('csrf') or ''),
        csrf()
    ):
        abort(403)


