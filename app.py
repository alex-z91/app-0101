@app.post('/admin/orders/<oid>/<action>')
@admin_only
def update_order(oid, action):
    verify_csrf()
    if action not in ('paid', 'cancelled'):
        abort(400)

    now = int(time.time())
    with conn() as db:
        db.execute('LOCK TABLE orders IN SHARE ROW EXCLUSIVE MODE')
        row = db.execute('SELECT status FROM orders WHERE id=%s', (oid,)).fetchone()
        if not row or row['status'] not in ('review', 'reserved'):
            return redirect(url_for('admin'))

        if action == 'cancelled':
            db.execute('DELETE FROM numbers WHERE order_id=%s', (oid,))
        db.execute(
            'UPDATE orders SET status=%s,confirmed_at=%s WHERE id=%s',
            (action, now, oid)
        )
        db.execute(
            'INSERT INTO audit(ts,order_id,action) VALUES(%s,%s,%s)',
            (now, oid, action)
        )
    return redirect(url_for('admin'))



